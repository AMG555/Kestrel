"""
Proper JS translation - handles comments, i18n fallbacks, and string literals.
Does NOT replace individual Chinese characters mid-word.
"""
import re, os, json

# ── Load en-US.json ──────────────────────────────────────────────────────────
with open("web/static/i18n/en-US.json", "r", encoding="utf-8-sig") as f:
    en_i18n = json.load(f)

def get_en(key):
    parts = key.split(".")
    d = en_i18n
    for p in parts:
        if isinstance(d, dict) and p in d:
            d = d[p]
        else:
            return None
    return d if isinstance(d, str) else None

# Flatten i18n for reverse lookup (Chinese -> English)
def flatten_i18n(d, prefix=""):
    result = {}
    for k, v in d.items():
        full_key = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            result.update(flatten_i18n(v, full_key))
        elif isinstance(v, str):
            if re.search(r"[\u4e00-\u9fff]", v):
                if v not in result:
                    result[v] = full_key
    return result

ZH_TO_KEY = flatten_i18n(en_i18n)

def zh_to_en(zh_text):
    """Look up Chinese text: first try i18n reverse lookup, then known translations."""
    if zh_text in ZH_TO_KEY:
        key = ZH_TO_KEY[zh_text]
        en = get_en(key)
        if en and not re.search(r"[\u4e00-\u9fff]", en):
            return en
    return KNOWN_TRANSLATIONS.get(zh_text)

