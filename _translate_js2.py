def translate_quoted_string(match):
    """Replace Chinese content inside a quoted string."""
    quote = match.group(1)
    content = match.group(2)
    close = match.group(3)
    
    if not re.search(r"[\u4e00-\u9fff]", content):
        return match.group(0)
    
    # Try exact lookup first
    en = zh_to_en(content)
    if en:
        return f"{quote}{en}{close}"
    
    # Try partial replacement of known phrases within the string
    result = content
    # Sort by length (longest first to avoid partial replacements)
    for zh, en_text in sorted(KNOWN_TRANSLATIONS.items(), key=lambda x: -len(x[0])):
        result = result.replace(zh, en_text)
    
    return f"{quote}{result}{close}"

def translate_line_comment(line):
    """Translate a comment line that starts with // or * Chinese."""
    # Extract the comment prefix and Chinese content
    match = re.match(r'^(\s*(?://|/?\*+)\s*)(.*)', line)
    if not match:
        return line
    prefix = match.group(1)
    text = match.group(2)
    
    if not re.search(r"[\u4e00-\u9fff]", text):
        return line
    
    # Try to translate the text
    en = zh_to_en(text.strip())
    if en:
        return f"{prefix}{en}"
    
    # Do word-by-word replacement
    result = text
    for zh, en_text in sorted(KNOWN_TRANSLATIONS.items(), key=lambda x: -len(x[0])):
        result = result.replace(zh, en_text)
    
    return f"{prefix}{result}"

def translate_content(content):
    """Main translation function for a JS file."""
    
    # 1. Replace strings in i18n fallback patterns like:
    #    chatTranslate('key', '中文')  or  t('key', '中文')  or  window.t('key')  or  '中文'
    # Pattern: translate('some.key', '中文fallback')
    def replace_i18n_call(m):
        key = m.group(1)
        quote = m.group(2)
        zh_text = m.group(3)
        en = get_en(key)
        if en and not re.search(r"[\u4e00-\u9fff]", en):
            return f"'{key}', {quote}{en}{quote}"
        en2 = zh_to_en(zh_text)
        if en2:
            return f"'{key}', {quote}{en2}{quote}"
        return m.group(0)
    
    content = re.sub(
        r"'([a-zA-Z][a-zA-Z0-9._]+)',\s*(['\"`])([\u4e00-\u9fff][^'\"` ]*['\"`\)].*?)\2",
        replace_i18n_call,
        content
    )
    
    # 2. Replace all quoted Chinese strings
    def repl_single(m):
        text = m.group(1)
        if not re.search(r"[\u4e00-\u9fff]", text):
            return m.group(0)
        en = zh_to_en(text)
        if en:
            return f"'{en}'"
        return f"'{translate_partial(text)}'"

    def repl_double(m):
        text = m.group(1)
        if not re.search(r"[\u4e00-\u9fff]", text):
            return m.group(0)
        en = zh_to_en(text)
        if en:
            return f'"{en}"'
        return f'"{translate_partial(text)}"'

    # Single-quoted strings
    content = re.sub(r"'((?:[^'\\]|\\.)*[\u4e00-\u9fff](?:[^'\\]|\\.)*)'", repl_single, content)
    # Double-quoted strings
    content = re.sub(r'"((?:[^"\\]|\\.)*[\u4e00-\u9fff](?:[^"\\]|\\.)*)"', repl_double, content)
    # Template literals (basic - non-nested)
    content = re.sub(r'`((?:[^`\\$]|\\.|\$(?!\{))*[\u4e00-\u9fff](?:[^`\\$]|\\.|\$(?!\{))*)`',
                     lambda m: f"`{translate_partial(m.group(1))}`", content)
    
    # 3. Replace Chinese in comments
    lines = content.split('\n')
    new_lines = []
    for line in lines:
        if not re.search(r"[\u4e00-\u9fff]", line):
            new_lines.append(line)
            continue
        
        stripped = line.lstrip()
        if stripped.startswith('//') or (stripped.startswith('*') and not stripped.startswith('*/')) or stripped.startswith('/*'):
            new_lines.append(translate_line_comment(line))
        else:
            # Inline comment: text // Chinese
            # Replace Chinese in the comment part (after //)
            def repl_inline_comment(m):
                prefix = m.group(1)
                comment = m.group(2)
                result = comment
                for zh, en_text in sorted(KNOWN_TRANSLATIONS.items(), key=lambda x: -len(x[0])):
                    result = result.replace(zh, en_text)
                return f"{prefix}{result}"
            
            new_line = re.sub(r'(//\s*)(.*[\u4e00-\u9fff].*)', repl_inline_comment, line)
            new_lines.append(new_line)
    
    return '\n'.join(new_lines)

def translate_partial(text):
    """Replace known Chinese phrases within a longer text."""
    result = text
    for zh, en_text in sorted(KNOWN_TRANSLATIONS.items(), key=lambda x: -len(x[0])):
        result = result.replace(zh, en_text)
    return result


