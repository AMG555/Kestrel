def translate_file(path):
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        content = f.read()
    
    before = len(re.findall(r'[\u4e00-\u9fff]', content))
    if before == 0:
        return 0, 0
    
    for zh, en in REPLACEMENTS:
        content = content.replace(zh, en)
    
    after = len(re.findall(r'[\u4e00-\u9fff]', content))
    replaced = before - after
    
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    
    return before, after

total_before = 0
total_after = 0
files_processed = 0

for root, dirs, files in os.walk("web/static/js"):
    dirs[:] = [d for d in dirs if d != "vendor"]
    for fname in sorted(files):
        if not fname.endswith((".js", ".cjs")):
            continue
        path = os.path.join(root, fname)
        before, after = translate_file(path)
        if before > 0:
            total_before += before
            total_after += after
            files_processed += 1
            if after > 0:
                print(f"  PARTIAL {path}: {before} -> {after} remaining")

print(f"\nDone: {files_processed} files processed")
print(f"Total Chinese chars: {total_before} -> {total_after} remaining")
print(f"Replaced: {total_before - total_after} chars")
