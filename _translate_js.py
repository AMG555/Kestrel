"""
Translate all Chinese text in web/static/js/*.js and *.test.cjs files.
Uses a comprehensive pattern-based replacement approach.
"""
import re, os, json, sys

# ── Load en-US.json for i18n key lookups ──────────────────────────────────
with open("web/static/i18n/en-US.json", "r", encoding="utf-8-sig") as f:
    en_i18n = json.load(f)

def get_en(key):
    parts = key.split(".")
    d = en_i18n
    for p in parts:
        if isinstance(d, dict) and p in d:
            d = d[p]
        else:
            return None
    return d if isinstance(d, str) else None

# ── Replace i18n key references that appear as fallback strings in JS ─────
def replace_i18n_in_js(content):
    """Replace patterns like i18n('key') or t('key') fallback strings."""
    # Pattern: some string in JS that matches an i18n key value in Chinese
    # We do a reverse lookup: find Chinese strings that equal a known i18n value
    def flatten_i18n(d, prefix=""):
        result = {}
        for k, v in d.items():
            full_key = f"{prefix}.{k}" if prefix else k
            if isinstance(v, dict):
                result.update(flatten_i18n(v, full_key))
            elif isinstance(v, str) and re.search(r'[\u4e00-\u9fff]', v):
                result[v] = full_key  # Chinese value -> key
        return result
    # Not using this for now — we use direct replacement
    return content

