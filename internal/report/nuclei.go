package report

import (
	"fmt"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"
	"kestrel/internal/database"
)

// NucleiTemplate represents a ProjectDiscovery Nuclei v3 detection template.
type NucleiTemplate struct {
	ID   string       `yaml:"id"`
	Info NucleiInfo   `yaml:"info"`
	HTTP []NucleiHTTP `yaml:"http"`
}

// NucleiInfo metadata section of Nuclei template.
type NucleiInfo struct {
	Name        string   `yaml:"name"`
	Author      string   `yaml:"author"`
	Severity    string   `yaml:"severity"`
	Description string   `yaml:"description,omitempty"`
	Tags        string   `yaml:"tags,omitempty"`
	Reference   []string `yaml:"reference,omitempty"`
}

// NucleiHTTP represents the HTTP request and matcher definition.
type NucleiHTTP struct {
	Method            string            `yaml:"method,omitempty"`
	Path              []string          `yaml:"path"`
	Headers           map[string]string `yaml:"headers,omitempty"`
	Body              string            `yaml:"body,omitempty"`
	MatchersCondition string            `yaml:"matchers-condition,omitempty"`
	Matchers          []NucleiMatcher   `yaml:"matchers,omitempty"`
}

// NucleiMatcher defines condition criteria for positive vulnerability matching.
type NucleiMatcher struct {
	Type      string   `yaml:"type"`
	Words     []string `yaml:"words,omitempty"`
	Status    []int    `yaml:"status,omitempty"`
	Condition string   `yaml:"condition,omitempty"`
}

func sanitizeID(s string) string {
	s = strings.TrimSpace(s)
	reg := regexp.MustCompile(`[^a-zA-Z0-9_\-]+`)
	return reg.ReplaceAllString(s, "-")
}

// GenerateNucleiTemplate converts a confirmed Vulnerability into an automated regression template.
func GenerateNucleiTemplate(v *database.Vulnerability) (string, error) {
	if v == nil {
		return "", fmt.Errorf("vulnerability is nil")
	}

	d := ExtractPoCDetails(v)

	vulnID := strings.ToLower(sanitizeID(v.ID))
	if vulnID == "" {
		vulnID = "finding"
	}
	templateID := fmt.Sprintf("kestrel-vuln-%s", vulnID)

	sev := strings.ToLower(strings.TrimSpace(v.Severity))
	if sev == "" {
		sev = "medium"
	}

	tags := []string{"kestrel", "regression", sev}
	if v.Type != "" {
		cleanedType := strings.ToLower(strings.ReplaceAll(v.Type, " ", "-"))
		tags = append(tags, cleanedType)
	}

	// Prepare path template
	pathTemplate := "{{BaseURL}}" + d.Path
	if !strings.HasPrefix(d.Path, "/") {
		pathTemplate = "{{BaseURL}}/" + d.Path
	}

	// Prepare matchers
	matchers := make([]NucleiMatcher, 0)
	if d.ExpectedIndicator != "" {
		matchers = append(matchers, NucleiMatcher{
			Type:  "word",
			Words: []string{d.ExpectedIndicator},
		})
	}
	matchers = append(matchers, NucleiMatcher{
		Type:   "status",
		Status: []int{200, 201, 204, 301, 302, 500},
	})

	httpReq := NucleiHTTP{
		Method:            d.Method,
		Path:              []string{pathTemplate},
		MatchersCondition: "and",
		Matchers:          matchers,
	}
	if len(d.Headers) > 0 {
		httpReq.Headers = d.Headers
	}
	if d.Body != "" {
		httpReq.Body = d.Body
	}

	tmpl := NucleiTemplate{
		ID: templateID,
		Info: NucleiInfo{
			Name:        v.Title,
			Author:      "kestrel-agent",
			Severity:    sev,
			Description: v.Description,
			Tags:        strings.Join(tags, ","),
			Reference: []string{
				"https://cwe.mitre.org/data/definitions/200.html",
			},
		},
		HTTP: []NucleiHTTP{httpReq},
	}

	data, err := yaml.Marshal(&tmpl)
	if err != nil {
		return "", fmt.Errorf("failed to marshal nuclei template: %w", err)
	}

	header := fmt.Sprintf("# Nuclei Regression Template generated by Kestrel\n# Vulnerability: %s\n# Target: %s\n\n", v.Title, v.Target)
	return header + string(data), nil
}
