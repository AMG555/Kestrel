package report

import (
	"fmt"
	"net/url"
	"regexp"
	"strings"
	"time"

	"kestrel/internal/database"
)

// PoCDetails represents the parsed HTTP transaction needed for reproduction.
type PoCDetails struct {
	Method            string
	TargetBase        string
	Path              string
	Headers           map[string]string
	Body              string
	ExpectedIndicator string
}

// ExtractPoCDetails extracts structured HTTP parameters from a vulnerability record.
func ExtractPoCDetails(v *database.Vulnerability) PoCDetails {
	details := PoCDetails{
		Method:     "GET",
		TargetBase: "http://localhost:8080",
		Path:       "/",
		Headers:    make(map[string]string),
	}

	if v == nil {
		return details
	}

	// 1. Parse Target
	targetStr := strings.TrimSpace(v.Target)
	if targetStr != "" {
		if !strings.HasPrefix(targetStr, "http://") && !strings.HasPrefix(targetStr, "https://") {
			targetStr = "http://" + targetStr
		}
		if u, err := url.Parse(targetStr); err == nil && u.Host != "" {
			details.TargetBase = fmt.Sprintf("%s://%s", u.Scheme, u.Host)
			if u.RequestURI() != "" && u.RequestURI() != "/" {
				details.Path = u.RequestURI()
			}
		}
	}

	combinedContext := v.ReproSteps + "\n" + v.Evidence

	// 2. Check for raw HTTP request format in ReproSteps
	// e.g.: POST /api/v1/auth HTTP/1.1
	rawHTTPRegex := regexp.MustCompile(`(?m)^(GET|POST|PUT|DELETE|PATCH|OPTIONS|HEAD)\s+([^\s]+)\s+HTTP\/[0-9.]+`)
	if match := rawHTTPRegex.FindStringSubmatch(combinedContext); len(match) > 2 {
		details.Method = strings.ToUpper(match[1])
		details.Path = match[2]

		// Extract headers and body from raw HTTP block
		rawLines := strings.Split(combinedContext, "\n")
		inHeaders := false
		inBody := false
		var bodyBuilder strings.Builder

		for _, line := range rawLines {
			line = strings.TrimRight(line, "\r")
			if rawHTTPRegex.MatchString(line) {
				inHeaders = true
				continue
			}
			if inHeaders {
				if strings.TrimSpace(line) == "" {
					inHeaders = false
					inBody = true
					continue
				}
				parts := strings.SplitN(line, ":", 2)
				if len(parts) == 2 {
					hdrKey := strings.TrimSpace(parts[0])
					hdrVal := strings.TrimSpace(parts[1])
					if !strings.EqualFold(hdrKey, "Host") && !strings.EqualFold(hdrKey, "Content-Length") {
						details.Headers[hdrKey] = hdrVal
					}
				}
			} else if inBody {
				bodyBuilder.WriteString(line + "\n")
			}
		}
		if bodyBuilder.Len() > 0 {
			details.Body = strings.TrimSpace(bodyBuilder.String())
		}
	}

	// 3. Fallback: Parse curl command if present
	if details.Method == "GET" && len(details.Headers) == 0 {
		curlRegex := regexp.MustCompile(`(?i)curl\s+(?:-X\s+([A-Z]+)\s+)?(?:["']?(https?:\/\/[^\s"']+)["']?)?`)
		if m := curlRegex.FindStringSubmatch(combinedContext); len(m) > 0 {
			if m[1] != "" {
				details.Method = strings.ToUpper(m[1])
			}
			if len(m) > 2 && m[2] != "" {
				if u, err := url.Parse(m[2]); err == nil && u.Host != "" {
					details.TargetBase = fmt.Sprintf("%s://%s", u.Scheme, u.Host)
					if u.RequestURI() != "" {
						details.Path = u.RequestURI()
					}
				}
			}
		}
	}

	// 4. Extract expected indicators from Evidence (e.g., SQL error, token, secret)
	if strings.TrimSpace(v.Evidence) != "" {
		lines := strings.Split(v.Evidence, "\n")
		for _, l := range lines {
			trimmed := strings.TrimSpace(l)
			if trimmed != "" && len(trimmed) < 120 && !strings.HasPrefix(trimmed, "#") && !strings.HasPrefix(trimmed, "HTTP/") {
				details.ExpectedIndicator = trimmed
				break
			}
		}
	}

	return details
}

// GeneratePoC compiles a Vulnerability into a standalone reproduction script (Python or Bash).
func GeneratePoC(v *database.Vulnerability, format string) (string, error) {
	if v == nil {
		return "", fmt.Errorf("vulnerability is nil")
	}

	d := ExtractPoCDetails(v)
	format = strings.ToLower(strings.TrimSpace(format))

	if format == "bash" || format == "sh" || format == "curl" {
		return generateBashPoC(v, d), nil
	}
	return generatePythonPoC(v, d), nil
}

func generatePythonPoC(v *database.Vulnerability, d PoCDetails) string {
	var sb strings.Builder

	sb.WriteString("#!/usr/bin/env python3\n")
	sb.WriteString("\"\"\"\n")
	sb.WriteString(fmt.Sprintf("Vulnerability PoC Reproduction Script\n"))
	sb.WriteString(fmt.Sprintf("Title:       %s\n", v.Title))
	sb.WriteString(fmt.Sprintf("Severity:    %s\n", strings.ToUpper(v.Severity)))
	sb.WriteString(fmt.Sprintf("Type:        %s\n", v.Type))
	sb.WriteString(fmt.Sprintf("Generated:   %s\n", time.Now().Format("2006-01-02 15:04:05 UTC")))
	sb.WriteString(fmt.Sprintf("Generated by Kestrel Security Assessment Engine\n"))
	sb.WriteString("\"\"\"\n\n")

	sb.WriteString("import sys\n")
	sb.WriteString("import argparse\n")
	sb.WriteString("import urllib.request\n")
	sb.WriteString("import urllib.error\n")
	sb.WriteString("import ssl\n\n")

	sb.WriteString("def main():\n")
	sb.WriteString("    parser = argparse.ArgumentParser(description='Reproduce " + escapePythonString(v.Title) + "')\n")
	sb.WriteString(fmt.Sprintf("    parser.add_argument('--target', '-t', default='%s', help='Target base URL')\n", escapePythonString(d.TargetBase)))
	sb.WriteString(fmt.Sprintf("    parser.add_argument('--path', '-p', default='%s', help='Request URI')\n", escapePythonString(d.Path)))
	sb.WriteString("    parser.add_argument('--insecure', '-k', action='store_true', default=True, help='Ignore SSL errors')\n")
	sb.WriteString("    args = parser.parse_args()\n\n")

	sb.WriteString("    base_url = args.target.rstrip('/')\n")
	sb.WriteString("    req_path = '/' + args.path.lstrip('/')\n")
	sb.WriteString("    full_url = base_url + req_path\n\n")

	sb.WriteString(fmt.Sprintf("    print(f'[*] Testing target: {full_url}')\n"))
	sb.WriteString(fmt.Sprintf("    print(f'[*] Vulnerability: %s [%s]')\n\n", escapePythonString(v.Title), strings.ToUpper(v.Severity)))

	// Prepare request
	if d.Body != "" {
		sb.WriteString(fmt.Sprintf("    body_data = b'''%s'''\n", escapePythonMultiline(d.Body)))
	} else {
		sb.WriteString("    body_data = None\n")
	}

	sb.WriteString(fmt.Sprintf("    req = urllib.request.Request(full_url, data=body_data, method='%s')\n", d.Method))
	if len(d.Headers) > 0 {
		for k, val := range d.Headers {
			sb.WriteString(fmt.Sprintf("    req.add_header('%s', '%s')\n", escapePythonString(k), escapePythonString(val)))
		}
	} else {
		sb.WriteString("    req.add_header('User-Agent', 'Kestrel-PoC-Verifier/1.0')\n")
	}
	sb.WriteString("    req.add_header('Connection', 'close')\n")

	sb.WriteString("\n    ctx = ssl.create_default_context()\n")
	sb.WriteString("    if args.insecure:\n")
	sb.WriteString("        ctx.check_hostname = False\n")
	sb.WriteString("        ctx.verify_mode = ssl.CERT_NONE\n\n")

	sb.WriteString("    try:\n")
	sb.WriteString("        with urllib.request.urlopen(req, context=ctx, timeout=15) as resp:\n")
	sb.WriteString("            status_code = resp.status\n")
	sb.WriteString("            resp_body = resp.read().decode('utf-8', errors='replace')\n")
	sb.WriteString("    except urllib.error.HTTPError as e:\n")
	sb.WriteString("        status_code = e.code\n")
	sb.WriteString("        resp_body = e.read().decode('utf-8', errors='replace')\n")
	sb.WriteString("    except Exception as e:\n")
	sb.WriteString("        print(f'[-] Connection failed: {e}', file=sys.stderr)\n")
	sb.WriteString("        sys.exit(2)\n\n")

	sb.WriteString("    print(f'[*] Response status code: {status_code}')\n")
	sb.WriteString("    print(f'[*] Response snippet: {resp_body[:300]}...')\n\n")

	// Matcher assertion check
	if d.ExpectedIndicator != "" {
		indicatorEscaped := escapePythonString(d.ExpectedIndicator)
		sb.WriteString(fmt.Sprintf("    indicator = '%s'\n", indicatorEscaped))
		sb.WriteString("    if indicator in resp_body:\n")
		sb.WriteString("        print(f'[+] VULNERABILITY CONFIRMED: Found expected indicator ({indicator}) in response!')\n")
		sb.WriteString("        sys.exit(0)\n")
		sb.WriteString("    else:\n")
		sb.WriteString("        print('[-] NOT CONFIRMED: Expected indicator was not observed (target may be patched).')\n")
		sb.WriteString("        sys.exit(1)\n")
	} else {
		sb.WriteString("    if 200 <= status_code < 400:\n")
		sb.WriteString("        print('[+] Request succeeded with 2xx/3xx. Inspect response snippet for manual confirmation.')\n")
		sb.WriteString("        sys.exit(0)\n")
		sb.WriteString("    else:\n")
		sb.WriteString("        print(f'[-] Target returned status {status_code}.')\n")
		sb.WriteString("        sys.exit(1)\n")
	}

	sb.WriteString("\nif __name__ == '__main__':\n")
	sb.WriteString("    main()\n")

	return sb.String()
}

func generateBashPoC(v *database.Vulnerability, d PoCDetails) string {
	var sb strings.Builder

	sb.WriteString("#!/usr/bin/env bash\n")
	sb.WriteString("# ====================================================================\n")
	sb.WriteString(fmt.Sprintf("# Vulnerability PoC Reproduction Script\n"))
	sb.WriteString(fmt.Sprintf("# Title:       %s\n", v.Title))
	sb.WriteString(fmt.Sprintf("# Severity:    %s\n", strings.ToUpper(v.Severity)))
	sb.WriteString(fmt.Sprintf("# Type:        %s\n", v.Type))
	sb.WriteString(fmt.Sprintf("# Generated:   %s\n", time.Now().Format("2006-01-02 15:04:05 UTC")))
	sb.WriteString("# ====================================================================\n\n")

	sb.WriteString("set -euo pipefail\n\n")
	sb.WriteString(fmt.Sprintf("TARGET=\"${1:-%s}\"\n", d.TargetBase))
	sb.WriteString(fmt.Sprintf("PATH_URI=\"%s\"\n", d.Path))
	sb.WriteString("FULL_URL=\"${TARGET%/}${PATH_URI}\"\n\n")

	sb.WriteString("echo \"[*] Testing target: ${FULL_URL}\"\n")
	sb.WriteString(fmt.Sprintf("echo \"[*] Vulnerability: %s\"\n\n", v.Title))

	var curlCmd strings.Builder
	curlCmd.WriteString(fmt.Sprintf("curl -s -i -k -X %s \"${FULL_URL}\"", d.Method))
	for k, val := range d.Headers {
		curlCmd.WriteString(fmt.Sprintf(" -H \"%s: %s\"", k, val))
	}
	if d.Body != "" {
		curlCmd.WriteString(fmt.Sprintf(" -d '%s'", strings.ReplaceAll(d.Body, "'", "'\\''")))
	}

	sb.WriteString("RESPONSE=$(" + curlCmd.String() + ")\n\n")
	sb.WriteString("echo \"[*] Response:\"\n")
	sb.WriteString("echo \"${RESPONSE}\" | head -n 25\n\n")

	if d.ExpectedIndicator != "" {
		indicatorEscaped := strings.ReplaceAll(d.ExpectedIndicator, "\"", "\\\"")
		sb.WriteString(fmt.Sprintf("if echo \"${RESPONSE}\" | grep -q \"%s\"; then\n", indicatorEscaped))
		sb.WriteString("    echo \"[+] VULNERABILITY CONFIRMED: Found indicator in response!\"\n")
		sb.WriteString("    exit 0\n")
		sb.WriteString("else\n")
		sb.WriteString("    echo \"[-] NOT CONFIRMED: Indicator not found in response.\"\n")
		sb.WriteString("    exit 1\n")
		sb.WriteString("fi\n")
	} else {
		sb.WriteString("echo \"[+] Request completed. Check response snippet above for verification.\"\n")
	}

	return sb.String()
}

func escapePythonString(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "'", "\\'")
	s = strings.ReplaceAll(s, "\n", "\\n")
	s = strings.ReplaceAll(s, "\r", "\\r")
	return s
}

func escapePythonMultiline(s string) string {
	return strings.ReplaceAll(s, "'''", "\\'''")
}
